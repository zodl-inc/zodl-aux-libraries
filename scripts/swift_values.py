"""Validate the twelve values of the ohttp group and write them XOR-encoded into one generated Swift file.

Commands:
  generate --mode release|example|none [--output PATH]
  example-env     print export lines for the public example values

Diagnostics go to stderr and never contain a value.
"""
import argparse
import hashlib
import ipaddress
import os
import re
import sys
import tempfile

NETWORKS = ("MAINNET", "TESTNET")
FIELDS = ("GATEWAY_HOST", "RELAY_URL", "KEYS_DNS_NAME", "SIGNING_PUBKEY", "RELAY_URLS", "RELAY_WEIGHTS_PUBKEY")
NAMES = ["APP_CONFIG_OHTTP_%s_%s" % (field, network) for network in NETWORKS for field in FIELDS]
KEY_DOMAIN = b"zodl-app-config-v1\0"
HEADER = "// Generated by scripts/swift_values.py. Never edit it, and never commit a version that holds values.\n"
DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "Sources", "ZodlAppConfig", "EncodedValues.generated.swift",
)

