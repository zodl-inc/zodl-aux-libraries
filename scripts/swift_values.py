# MARK: Validation

DNS_LABEL = re.compile(r"[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?")
DNS_LABEL_ANY_CASE = re.compile(r"[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?")


def is_dns_name(value, any_case=False):
    if not value or len(value) > 253:
        return False
    pattern = DNS_LABEL_ANY_CASE if any_case else DNS_LABEL
    return all(pattern.fullmatch(label) for label in value.split("."))


def host_rule_problem(value):
    if value != value.lower():
        return "must be lower-case"
    if not is_dns_name(value):
        return "must be a bare DNS host name (no scheme, port, path, whitespace or trailing dot)"
    return None


def relay_rule_problem(value):
    rule = "must be https://host[:port][/path] without userinfo, query, fragment, backslash, whitespace or control characters"
    if not value.startswith("https://"):
        return rule
    if any(ord(c) <= 0x20 or ord(c) >= 0x7F or c in "\\?#" for c in value):
        return rule
    rest = value[len("https://"):]
    authority = rest.split("/", 1)[0]
    if not authority or "@" in authority:
        return rule
    if authority.startswith("["):
        end = authority.find("]")
        if end < 0:
            return rule
        host, port = authority[1:end], authority[end + 1:]
        if not re.fullmatch(r"[0-9a-fA-F:.]+", host):
            return rule
        try:
            ipaddress.IPv6Address(host)
        except ValueError:
            return rule
        if port and not port.startswith(":"):
            return rule
        port = port[1:] if port else None
    else:
        host, _, port = authority.partition(":")
        port = port if ":" in authority else None
        try:
            ipaddress.IPv4Address(host)
        except ValueError:
            if not is_dns_name(host, any_case=True):
                return rule
    if port is not None and not (re.fullmatch(r"[0-9]{1,5}", port) and 0 < int(port) < 65536):
        return rule
    return None


MAX_RELAYS = 8


def relay_identity(url):
    """The relay as zodl-ohttp-client tells relays apart, near enough for a duplicate check: lower case, no :443,
    no trailing slash."""
    url = url.lower().rstrip("/")
    scheme, _, rest = url.partition("://")
    authority, slash, path = rest.partition("/")
    if authority.endswith(":443"):
        authority = authority[:-4]
    return authority + slash + path


def relay_list(value):
    """The URLs of a relay list as zodl-ohttp-client >= 2.2.0 reads relay_url: split where ',' is followed by
    'https://'."""
    entries = []
    rest = value
    while True:
        at = rest.find(",https://")
        if at < 0:
            entries.append(rest)
            return entries
        entries.append(rest[:at])
        rest = rest[at + 1:]


def relay_list_rule_problem(value):
    """A relay list: relay URLs separated by ',' (each after the first starting https://), at most 8, no relay
    twice. Every relay gets an equal share."""
    rule = "must be relay URLs separated by ',' (at most 8, no relay twice)"
    entries = relay_list(value)
    if len(entries) > MAX_RELAYS:
        return rule
    for i, url in enumerate(entries):
        if relay_rule_problem(url) or (i + 1 < len(entries) and url.endswith(",")):
            return rule
    identities = [relay_identity(url) for url in entries]
    if len(set(identities)) != len(identities):
        return rule
    return None


# Ed25519 point checks (RFC 8032 section 5.1.3), pure integer arithmetic.
P = 2 ** 255 - 19
D = (-121665 * pow(121666, P - 2, P)) % P
SQRT_M1 = pow(2, (P - 1) // 4, P)


def decompress(raw):
    y = int.from_bytes(raw, "little")
    sign = y >> 255
    y &= (1 << 255) - 1
    if y >= P:
        return None
    u = (y * y - 1) % P
    v = (D * y * y + 1) % P
    x = (u * pow(v, 3, P) * pow(u * pow(v, 7, P), (P - 5) // 8, P)) % P
    if (v * x * x - u) % P != 0:
        if (v * x * x + u) % P != 0:
            return None
        x = (x * SQRT_M1) % P
    if x == 0 and sign:
        return None
    if x & 1 != sign:
        x = P - x
    return (x, y)


def add(a, b):
    (x1, y1), (x2, y2) = a, b
    t = (D * x1 * x2 * y1 * y2) % P
    x3 = ((x1 * y2 + x2 * y1) * pow(1 + t, P - 2, P)) % P
    y3 = ((y1 * y2 + x1 * x2) * pow(1 - t, P - 2, P)) % P
    return (x3, y3)


def signing_key_rule_problem(value):
    if not re.fullmatch(r"[0-9a-fA-F]{64}", value):
        return "must be 64 hex digits"
    point = decompress(bytes.fromhex(value))
    if point is None:
        return "must be a valid Ed25519 public key"
    for _ in range(3):
        point = add(point, point)
    if point == (0, 1):
        return "must not be a small-order Ed25519 point"
    return None


def problem_for(name, value):
    field = name[len("APP_CONFIG_OHTTP_"):].rsplit("_", 1)[0]
    if field in ("GATEWAY_HOST", "KEYS_DNS_NAME"):
        return host_rule_problem(value)
    if field == "RELAY_URL":
        return relay_rule_problem(value)
    if field == "RELAY_URLS":
        return relay_list_rule_problem(value)
    # SIGNING_PUBKEY and RELAY_WEIGHTS_PUBKEY: raw Ed25519 public keys.
    return signing_key_rule_problem(value)


def validate(values):
    """Return the problems as (name, rule); empty when valid. All twelve values are required."""
    problems = []
    for name in NAMES:
        value = values.get(name)
        if not value:
            problems.append((name, "missing (a release needs all twelve values)"))
            continue
        rule = problem_for(name, value)
        if rule:
            problems.append((name, rule))
    count = len(FIELDS)
    mainnet = {values[name].lower(): name for name in NAMES[:count] if values.get(name)}
    for name in NAMES[count:]:
        if not values.get(name):
            continue
        other = mainnet.get(values[name].lower())
        if other:
            problems.append((name, "must differ from every mainnet value (it equals %s)" % other))
    for network in NETWORKS:
        # The relay weights key signs a block of its own: it must not be the network's signing key. Across networks
        # every testnet value already differs from every mainnet value (above).
        weights = values.get("APP_CONFIG_OHTTP_RELAY_WEIGHTS_PUBKEY_%s" % network)
        signing = values.get("APP_CONFIG_OHTTP_SIGNING_PUBKEY_%s" % network)
        if weights and signing and weights.lower() == signing.lower():
            problems.append(("APP_CONFIG_OHTTP_RELAY_WEIGHTS_PUBKEY_%s" % network,
                             "must differ from SIGNING_PUBKEY_%s" % network))
    relays = {}
    for network in NETWORKS:
        single = values.get("APP_CONFIG_OHTTP_RELAY_URL_%s" % network)
        name = "APP_CONFIG_OHTTP_RELAY_URLS_%s" % network
        if not values.get(name) or not single or problem_for(name, values[name]) or relay_rule_problem(single):
            continue
        entries = relay_list(values[name])
        # The client fetches the signed key configuration through the first relay listed, and older apps use
        # RELAY_URL alone: they must be the same relay.
        if relay_identity(entries[0]) != relay_identity(single):
            problems.append((name, "must list RELAY_URL_%s first" % network))
        relays[network] = {relay_identity(url) for url in entries}
    if len(relays) == 2 and relays["MAINNET"] & relays["TESTNET"]:
        problems.append(("APP_CONFIG_OHTTP_RELAY_URLS_TESTNET", "must share no relay with RELAY_URLS_MAINNET"))
    return problems


# MARK: Output

def array(numbers):
    return "[" + ", ".join("0x%02x" % n for n in numbers) + "]"


def encode(values):
    """Return the generated Swift source. None gives the form without values."""
    if values is None:
        lines = [
            HEADER.rstrip("\n"),
            "enum EncodedValues {",
            "    static let key: [UInt8] = []",
            "    static let mainnet: [[UInt8]]? = nil",
            "    static let testnet: [[UInt8]]? = nil",
            "}",
        ]
        return "\n".join(lines) + "\n"
    ordered = [values[name] for name in NAMES]
    key = hashlib.sha256(KEY_DOMAIN + "\0".join(ordered).encode("utf-8")).digest()

    def xor(value):
        return [b ^ key[i % len(key)] for i, b in enumerate(value.encode("utf-8"))]

    lines = [HEADER.rstrip("\n"), "enum EncodedValues {", "    static let key: [UInt8] = " + array(key)]
    for index, network in enumerate(NETWORKS):
        lines.append("    static let %s: [[UInt8]]? = [" % network.lower())
        count = len(FIELDS)
        lines.extend("        %s," % array(xor(v)) for v in ordered[index * count:index * count + count])
        lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_if_changed(path, content):
    data = content.encode("utf-8")
    try:
        with open(path, "rb") as handle:
            if handle.read() == data:
                return
    except FileNotFoundError:
        pass
    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, exist_ok=True)
    fd, temp = tempfile.mkstemp(dir=directory, prefix=".app-config-")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.replace(temp, path)
    except BaseException:
        if os.path.exists(temp):
            os.unlink(temp)
        raise


# MARK: Commands

def command_generate(args):
    if args.mode == "none":
        content = encode(None)
    elif args.mode == "example":
        content = encode(EXAMPLE_VALUES)
    else:
        values = {name: os.environ[name] for name in NAMES if os.environ.get(name)}
        problems = validate(values)
        if problems:
            for name, rule in problems:
                print("error: %s: %s" % (name, rule), file=sys.stderr)
            return 1
        content = encode(values)
    write_if_changed(args.output, content)
    return 0


def command_example_env(args):
    for name in NAMES:
        print("export %s='%s'" % (name, EXAMPLE_VALUES[name]))
    return 0


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    generate = sub.add_parser("generate")
    generate.add_argument("--mode", required=True, choices=("release", "example", "none"))
    generate.add_argument("--output", default=DEFAULT_OUTPUT)
    generate.set_defaults(run=command_generate)
    example_env = sub.add_parser("example-env")
    example_env.set_defaults(run=command_example_env)
    args = parser.parse_args(argv)
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
