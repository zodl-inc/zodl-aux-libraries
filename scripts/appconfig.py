"""Android side of the app config: the Kotlin source generated from config/schema.json and the environment.

  appconfig.py kotlin OUT_DIR   write <package path>/AppConfig.kt under OUT_DIR (Gradle task generateConfig)
  appconfig.py env-names        print the APP_CONFIG_* names, one per line (input of the aws-secrets step)
  appconfig.py digest           print the sha256 of all values in schema order, so the Publish jobs can check
                                that both platforms got the same values (a digest, never a value)

Every value comes from APP_CONFIG_<GROUP>_<KEY>. A required group needs all of its keys. Values are printable
ASCII without quotes, backslashes or '$'. The ohttp group must also pass the rules of scripts/swift_values.py,
the ones the Swift release applies, so both platforms accept the same values. Errors name the variable, never
the value. The Swift package is generated by scripts/swift_values.py, not by this script.
"""
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMA = os.path.join(ROOT, "config", "schema.json")
HEADER = "Generated from config/schema.json. Values are filled in CI only; never commit them."

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import swift_values  # noqa: E402


def load(path=SCHEMA):
    with open(path) as fh:
        schema = json.load(fh)
    if not schema.get("groups"):
        sys.exit("Schema has no groups")
    for group, spec in schema["groups"].items():
        if not (group.isidentifier() and group.islower() and group.isascii()):
            sys.exit(f"Bad group name {group!r}: lowercase identifier expected")
        if not spec.get("keys"):
            sys.exit(f"Group {group} has no keys")
        for key in spec["keys"]:
            if not (key.replace("_", "").isalnum() and key.isupper() and key.isascii() and key[0].isalpha()):
                sys.exit(f"Bad key name {key!r} in group {group}: UPPER_SNAKE expected")
        if len(set(spec["keys"])) != len(spec["keys"]):
            sys.exit(f"Duplicate key in group {group}")
    return schema


def env_name(group, key):
    return f"APP_CONFIG_{group.upper()}_{key}"


def values(schema):
    out = {}
    for group, spec in schema["groups"].items():
        # No strip: both platforms must see byte-identical values (the Swift release does not strip either).
        vals = {k: os.environ.get(env_name(group, k), "") for k in spec["keys"]}
        missing = [env_name(group, k) for k, v in vals.items() if not v]
        if spec.get("required") and missing:
            sys.exit(f"Missing required configuration: {', '.join(missing)}")
        for k, v in vals.items():
            if any(c in '"\\$' or not (0x21 <= ord(c) <= 0x7E) for c in v):
                sys.exit(f"Illegal character in {env_name(group, k)}")
        if group == "ohttp":
            problems = swift_values.validate({env_name(group, k): v for k, v in vals.items() if v})
            if problems:
                sys.exit("\n".join(f"error: {name}: {rule}" for name, rule in problems))
        out[group] = vals
    return out


def kotlin(schema, out_dir):
    vals = values(schema)
    body = []
    for group, kv in vals.items():
        body.append(f"    object {group.capitalize()} {{")
        body += [f'        const val {k}: String = "{v}"' for k, v in kv.items()]
        body.append("    }")
    pkg = schema["kotlin_package"]
    path = os.path.join(out_dir, *pkg.split("."), f"{schema['root']}.kt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(f"package {pkg}\n\n/** {HEADER} */\nobject {schema['root']} {{\n" + "\n".join(body) + "\n}\n")


def main(argv):
    schema = load()
    cmd = argv[1] if len(argv) > 1 else ""
    if cmd == "kotlin" and len(argv) == 3:
        kotlin(schema, argv[2])
    elif cmd == "env-names" and len(argv) == 2:
        print("\n".join(env_name(g, k) for g, s in schema["groups"].items() for k in s["keys"]))
    elif cmd == "digest" and len(argv) == 2:
        joined = "\0".join(v for kv in values(schema).values() for v in kv.values())
        print(hashlib.sha256(joined.encode("utf-8")).hexdigest())
    else:
        sys.exit(__doc__)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
